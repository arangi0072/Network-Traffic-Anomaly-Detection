import os, json, glob
import numpy as np
import pandas as pd
import streamlit as st
import joblib
import tensorflow as tf

st.set_page_config(page_title="DeepShield IDS", page_icon="🛡️", layout="wide")
st.title("🛡️ DeepShield — Deep Learning Intrusion Detection")
st.caption("CA Project • CNN vs RNN vs LSTM vs GRU • CIC-IDS2017")

ART = "artifacts"
required = ["scaler.joblib", "features.json"]
if not all(os.path.exists(os.path.join(ART, f)) for f in required):
    st.warning("No trained artifacts found. First download the dataset into data/ and run `python train.py`.")
    st.code("python train.py --epochs 8 --max-rows 60000")
    st.stop()

scaler = joblib.load(os.path.join(ART, "scaler.joblib"))
with open(os.path.join(ART, "features.json")) as f:
    features = json.load(f)

available = [m for m in ["CNN", "RNN", "LSTM", "GRU"]
             if os.path.exists(os.path.join(ART, f"{m.lower()}_model.keras"))]
if not available:
    st.error("No model files found. Run training first.")
    st.stop()

with st.sidebar:
    st.header("Prediction settings")
    selected = st.selectbox("Choose model", available)
    st.write("Threshold: 0.50")
    st.caption("Prediction is based on the trained model and selected dataset features.")

model = tf.keras.models.load_model(os.path.join(ART, f"{selected.lower()}_model.keras"))
uploaded = st.file_uploader("Upload a CSV with the same numeric traffic features used for training", type=["csv"])

if uploaded:
    df = pd.read_csv(uploaded, low_memory=False)
    st.subheader("Uploaded data")
    st.dataframe(df.head(10), use_container_width=True)
    aligned = pd.DataFrame(index=df.index)
    missing = []
    for col in features:
        if col in df.columns:
            aligned[col] = pd.to_numeric(df[col], errors="coerce")
        else:
            aligned[col] = np.nan
            missing.append(col)
    aligned = aligned.replace([np.inf, -np.inf], np.nan)
    aligned = aligned.fillna(aligned.median(numeric_only=True)).fillna(0)
    if missing:
        st.info(f"{len(missing)} expected feature(s) were missing and filled with zero/column median. For best results upload a CSV from the same dataset.")
    x = scaler.transform(aligned[features]).astype("float32")[..., np.newaxis]
    prob = model.predict(x, verbose=0).ravel()
    out = df.copy()
    out["attack_probability"] = prob.round(4)
    out["prediction"] = np.where(prob >= 0.5, "SUSPICIOUS / ATTACK", "BENIGN")
    a, b, c = st.columns(3)
    a.metric("Rows analyzed", f"{len(out):,}")
    b.metric("Predicted suspicious", f"{(prob >= 0.5).sum():,}")
    c.metric("Model", selected)
    st.dataframe(out, use_container_width=True)
    st.download_button("Download predictions CSV", out.to_csv(index=False).encode("utf-8"),
                       file_name="deepshield_predictions.csv", mime="text/csv")
else:
    st.info("Upload a CSV to run predictions. The interface becomes active after you train the models.")
    metrics_path = os.path.join(ART, "metrics.json")
    if os.path.exists(metrics_path):
        with open(metrics_path) as f:
            metrics = json.load(f)
        st.subheader("Held-out test-set comparison")
        mdf = pd.DataFrame([{k: row[k] for k in ["model", "accuracy", "precision", "recall", "f1"]} for row in metrics])
        st.dataframe(mdf.style.format({c: "{:.3f}" for c in ["accuracy", "precision", "recall", "f1"]}),
                     use_container_width=True)
        st.bar_chart(mdf.set_index("model")[["accuracy", "precision", "recall", "f1"]])
        st.caption("Metrics are generated by your own training run; results vary with data and settings.")
